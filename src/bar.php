function tbl(&$cod,&$tabl,$dv){
  global $tbc;
  for($i=0;$i<3;$i++){
    $h1 = $tbc[$cod][$i*2];
    $h2 = $tbc[$cod][$i*2+1];
    if($dv)
      $tabl .= "<tr><td width=100% id=v{$h1}b></td></tr><tr><td id=v{$h2}w></td></tr>";
    else 
      $tabl .= "<td id=h{$h1}b></td><td id=h{$h2}w></td>";
  }
  if($cod == 106)
    if($dv)
      $tabl .= "<tr><td id=v2b></td></tr>";
    else
      $tabl .= "<td id=h2b></td>";
}

